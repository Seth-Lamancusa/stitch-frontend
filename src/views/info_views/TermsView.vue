<script setup>
import InfoViewLayout from '../../components/layouts/InfoViewLayout.vue';
import { ref, onMounted, onBeforeUnmount } from 'vue';

// Track active section for navigation highlighting
const activeSection = ref('terms-and-conditions');

// Define section refs
const termsAndConditionsSection = ref(null);
const privacyPolicySection = ref(null);

// Function to scroll to section
const scrollToSection = (sectionId) => {
  const section = document.getElementById(sectionId);
  if (section) {
    section.scrollIntoView({ behavior: 'smooth' });
    activeSection.value = sectionId;
  }
};

// Track active section based on scroll position
const handleScroll = () => {
  const sections = [
    { ref: termsAndConditionsSection, id: 'terms-and-conditions' },
    { ref: privacyPolicySection, id: 'privacy-policy' }
  ];

  for (const section of sections) {
    if (!section.ref.value) continue;
    
    const rect = section.ref.value.getBoundingClientRect();
    if (rect.top <= 150 && rect.bottom >= 150) {
      activeSection.value = section.id;
      break;
    }
  }
};

onMounted(() => {
  // Add scroll event listener
  window.addEventListener('scroll', handleScroll);
  
  // Initial scroll check
  handleScroll();
});

onBeforeUnmount(() => {
  // Remove scroll event listener
  window.removeEventListener('scroll', handleScroll);
});
</script>

